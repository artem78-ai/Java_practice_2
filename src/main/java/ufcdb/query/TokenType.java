package ufcdb.query;

/** Виды токенов SQL-запроса. */
public enum TokenType {
    /** Слово: ключевое слово, имя таблицы или столбца, TRUE/FALSE/NULL. */
    WORD,
    /** Число, например 25000 или -3.5. */
    NUMBER,
    /** Строка в одинарных кавычках (кавычки в токен не входят). */
    STRING,
    /** Символ или оператор: ( ) , * ; = != <> < > <= >=. */
    SYMBOL
}
